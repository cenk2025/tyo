/**
 * Fill occupations.isco_group where the ESCO import left it empty, and write
 * the result as SQL to run in the Supabase SQL editor.
 *
 *   node scripts/fill-isco-groups.mjs
 *   node scripts/fill-isco-groups.mjs --out supabase/esco-import/05_fill_isco_group.sql
 *
 * About 40% of occupations (1,255 of 3,046) were imported with no isco_group:
 * they are ESCO's narrower occupations ("diet cook" under "cook"). Every ESCO
 * occupation has a code whose first four digits are its ISCO-08 unit group —
 * "diet cook" is 5120.1.1, ISCO 5120 — so the group can be recovered without a
 * re-import by asking the ESCO API for each code, pinned to v1.2.1 like the
 * rest of the data. Checked before use: on 40 occupations that already had an
 * isco_group, the code prefix matched it 40/40.
 *
 * Read-only against Supabase (the anon key is enough): it writes a SQL file,
 * not the database, so the update is reviewed and run by hand like the
 * migrations. Re-runnable; the generated UPDATE only touches rows still null.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";

if (existsSync(".env.local")) {
  for (const line of readFileSync(".env.local", "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].trim().replace(/^["']|["']$/g, "");
  }
}
const die = (msg) => { console.error(`\n  ${msg}\n`); process.exit(1); };
const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
if (!url || !key) die("Set NEXT_PUBLIC_SUPABASE_URL and a Supabase key (.env.local).");
const db = createClient(url, key, { auth: { persistSession: false } });

const outIdx = process.argv.indexOf("--out");
const OUT = outIdx > -1 ? process.argv[outIdx + 1] : "supabase/esco-import/05_fill_isco_group.sql";
const ESCO_API = "https://ec.europa.eu/esco/api/resource/occupation";
const ESCO_VERSION = "v1.2.1";
const CONCURRENCY = 8;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function nullOccupations() {
  const out = [];
  for (let from = 0; ; from += 1000) {
    const { data, error } = await db
      .from("occupations")
      .select("concept_uri, preferred_label_en")
      .is("isco_group", null)
      .order("concept_uri")
      .range(from, from + 999);
    if (error) die(error.message);
    out.push(...data);
    if (data.length < 1000) return out;
  }
}

/** ESCO code for one occupation, e.g. "5120.1.1"; null when the API has none. */
async function escoCode(uri) {
  const q = new URLSearchParams({ uri, language: "en", selectedVersion: ESCO_VERSION });
  for (let attempt = 1; attempt <= 4; attempt++) {
    try {
      const res = await fetch(`${ESCO_API}?${q}`);
      if (res.status === 404) return null;
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const json = await res.json();
      return typeof json.code === "string" ? json.code : null;
    } catch (err) {
      if (attempt === 4) throw err;
      await sleep(1000 * 2 ** attempt);
    }
  }
  return null;
}

const rows = await nullOccupations();
console.log(`${rows.length} occupations without isco_group`);

const found = [];
const missing = [];
let done = 0;
const queue = [...rows];
await Promise.all(
  Array.from({ length: CONCURRENCY }, async () => {
    for (let row = queue.shift(); row; row = queue.shift()) {
      const code = await escoCode(row.concept_uri);
      const isco = code?.match(/^(\d{4})/)?.[1] ?? null;
      (isco ? found : missing).push({ ...row, code, isco });
      if (++done % 100 === 0) console.log(`  ${done}/${rows.length}`);
    }
  })
);
found.sort((a, b) => a.concept_uri.localeCompare(b.concept_uri));

const esc = (s) => s.replace(/'/g, "''");
const sql = `-- ============================================================================
-- SkillPath — fill occupations.isco_group for ESCO narrower occupations
-- Generated by scripts/fill-isco-groups.mjs on ${new Date().toISOString().slice(0, 10)}
-- from the ESCO API (${ESCO_VERSION}): isco_group = first four digits of the
-- occupation's ESCO code. ${found.length} rows; ${missing.length} had no code.
-- Only rows that are still null are touched. Re-runnable.
-- ============================================================================

update public.occupations as o
set isco_group = v.isco
from (values
${found.map((r) => `  ('${esc(r.concept_uri)}', '${r.isco}')`).join(",\n")}
) as v(concept_uri, isco)
where o.concept_uri = v.concept_uri
  and o.isco_group is null;

-- Check: should return 0 (or the ${missing.length} occupations the API had no code for).
select count(*) as still_missing from public.occupations where isco_group is null;
`;
writeFileSync(OUT, sql);
console.log(`\nWrote ${OUT}: ${found.length} updates, ${missing.length} without a code.`);
if (missing.length) console.log("No code:", missing.slice(0, 10).map((m) => m.preferred_label_en).join("; "));
